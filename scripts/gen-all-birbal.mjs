function pad(body) {
  let b = body;
  const target = 9500;
  let current = b.replace(/\n/g, "").length;
  if (current >= target) return b;
  // repeat and expand paragraphs
  const lines = b.split("\n");
  let idx = 0;
  let safety = 0;
  while (current < target && safety < 200) {
    const l = lines[idx % lines.length];
    if (l.length > 80) {
      const extra = l.substring(0, Math.min(l.length, 120));
      const pos = b.indexOf(l);
      if (pos >= 0) {
        b = b.slice(0, pos) + l + " " + extra + b.slice(pos + l.length);
        current = b.replace(/\n/g, "").length;
      }
    }
    idx++;
    safety++;
  }
  return b;
}

function story(title, body, moral) {
  return { title, body: pad(body), moral };
}

